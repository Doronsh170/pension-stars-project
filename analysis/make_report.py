#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Stage 3 - assemble the Hebrew research report (analysis/REPORT_he.md) from the
CSV outputs of the previous stages.
"""
import csv, os, statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))

def read(name):
    return list(csv.DictReader(open(os.path.join(HERE, name), encoding="utf-8-sig")))

events = read("events.csv")
strat = read("strategy_summary.csv")
risk = read("risk_summary.csv")

CAT_ORDER = [
    ("gemel", 'קרנות השתלמות | כללי'),
    ("gemel", 'תגמולים ואישית לפיצויים | כללי'),
    ("gemel", 'מרכזית לפיצויים | כללי'),
    ("gemel", 'קרנות השתלמות | מניות'),
    ("gemel", 'תגמולים ואישית לפיצויים | מניות'),
    ("gemel", 'קרנות השתלמות | אג"ח'),
    ("gemel", 'תגמולים ואישית לפיצויים | אג"ח'),
    ("pension", 'קרנות חדשות'),
    ("pension", 'קרנות כלליות'),
]
DOM_HE = {"gemel": "גמל", "pension": "פנסיה"}

def cshow(cat):
    # avoid the '|' char breaking markdown tables
    return cat.replace(" | ", " – ")

def fnum(x, suf="%"):
    if x is None or x == "":
        return "—"
    return f"{float(x):.1f}{suf}"

# ---------- pooled persistence ----------
pool = {1: [], 2: [], 3: []}
beat = {1: [], 2: [], 3: []}
topq = {1: [], 2: [], 3: []}
no1 = {1: [], 2: [], 3: []}
bot = {1: [], 2: [], 3: []}
for e in events:
    for k in (1, 2, 3):
        st = e.get(f"y{k}_status")
        if st != "present":
            continue
        pc = float(e[f"y{k}_percentile"]); rk = int(e[f"y{k}_rank"]); n = int(e[f"y{k}_n"])
        pool[k].append(pc)
        beat[k].append(1 if rk <= n / 2.0 else 0)
        topq[k].append(1 if rk <= n / 4.0 else 0)
        no1[k].append(1 if rk == 1 else 0)
        bot[k].append(1 if rk > n / 2.0 else 0)

def mean(l): return statistics.mean(l) if l else float("nan")

lines = []
w = lines.append

w("# האם כדאי לרדוף אחרי התשואות? מחקר אמפירי על קופות גמל וקרנות פנסיה")
w("")
w("**עודכן:** יולי 2026 · **נתוני מקור:** גמלנט / פנסיהנט (רשות שוק ההון) · "
  "**תקופה:** 1999–2025 (גמל), 2011–2025 (פנסיה)")
w("")
w("## השאלה")
w("")
w("חוסך רואה בכל תחילת שנה את דירוג התשואות של השנה שחלפה, מזהה את הקופה "
  "שהובילה בקטגוריה שלו, ומעביר אליה את כספו. **האם המהלך הזה משתלם לאורך זמן, "
  "או שמדובר ב\"רדיפה אחרי תשואות\" — החלטה המבוססת על ביצועי עבר בלבד?**")
w("")
w("## שיטה בקצרה")
w("")
w("- תשואה שנתית לכל קופה חושבה משרשור 12 התשואות החודשיות (`MONTHLY_YIELD`); "
  "נכללו רק שנים עם 12 חודשי דיווח מלאים.")
w("- **קטגוריה** = סיווג הקופה + מסלול ההשקעה, כדי להשוות \"תפוח לתפוח\" "
  "(למשל *קרנות השתלמות – מסלול כללי*). נדרשו לפחות 8 קופות בקטגוריה כדי "
  "שדירוג \"מקום ראשון\" יהיה בעל משמעות.")
w("- לכל שנת **איתות** Y מזוהה הקופה שדורגה ראשונה, ואז עוקבים אחרי **אותה קופה** "
  "(לפי מזהה) בשנים Y+1, Y+2, Y+3: מה הייתה תשואתה ובאיזה מקום דורגה בקטגוריה.")
w("- *אחוזון* 100 = מקום ראשון, 0 = מקום אחרון. תחת השערת \"אין יתרון מתמשך\", "
  "האחוזון הצפוי בשנה שאחרי הוא 50 (הטלת מטבע).")
w("")

# ---------- headline persistence table ----------
w("## ממצא 1 — ההובלה נשחקת: המנצחת של אשתקד היא הימור, לא ודאות")
w("")
w("מה קרה, בממוצע על פני **כל הקטגוריות וכל השנים**, לקופה שדורגה ראשונה — "
  "בשנים שאחרי:")
w("")
w("| אופק | מס' מקרים | אחוזון ממוצע בשנה שאחרי | הכתה את חציון הקטגוריה | "
  "נשארה ברבעון העליון | נשארה מקום 1 | צנחה למחצית התחתונה |")
w("|---|---:|---:|---:|---:|---:|---:|")
for k in (1, 2, 3):
    w(f"| +{k} שנים | {len(pool[k])} | {mean(pool[k]):.0f} | "
      f"{mean(beat[k])*100:.0f}% | {mean(topq[k])*100:.0f}% | "
      f"{mean(no1[k])*100:.0f}% | {mean(bot[k])*100:.0f}% |")
w("")
w(f"**מה רואים:** בשנה שאחרי האיתות הקופה המובילה נוחתת בממוצע סביב האחוזון "
  f"~{mean(pool[1]):.0f} — טוב מהטלת מטבע (50), אבל רחוק מלשמור על הצמרת. רק "
  f"~{mean(no1[1])*100:.0f}% מהמנצחות חוזרות למקום הראשון, והנתון קורס לכ-"
  f"{mean(no1[3])*100:.0f}% תוך שלוש שנים. במקביל, כ-{mean(bot[1])*100:.0f}%–"
  f"{mean(bot[3])*100:.0f}% מהמנצחות מוצאות את עצמן במחצית **התחתונה** של הקטגוריה. "
  "היתרון קיים אך חלש ומתפוגג — לא בסיס אמין להחלטה.")
w("")

# ---------- money table ----------
w("## ממצא 2 — \"היתרון\" הכספי הוא בעיקר סיכון, לא כישרון")
w("")
w("סימולציה: חוסך שבכל שנה עובר לקופה שהובילה אשתקד (**\"רודף\"**), מול חוסך "
  "שמחזיק את ממוצע הקטגוריה (**\"נשאר\"**). תשואה שנתית ממוצעת (CAGR):")
w("")
w("| קטגוריה | שנים | רודף (CAGR) | נשאר (CAGR) | פער שנתי |")
w("|---|---:|---:|---:|---:|")
strat_by = {(s["domain"], s["category"]): s for s in strat}
for dom, cat in CAT_ORDER:
    s = strat_by.get((dom, cat))
    if not s: continue
    w(f"| {DOM_HE[dom]} · {cshow(cat)} | {s['n_years']} | {s['chase_annualized_pct']}% | "
      f"{s['stay_annualized_pct']}% | {'+' if float(s['gap_annualized_pp'])>=0 else ''}{s['gap_annualized_pp']} נק' |")
gaps = [float(s["gap_annualized_pp"]) for s in strat]
w("")
w(f"הרדיפה \"ניצחה\" בכל {len(gaps)} הקטגוריות — אבל שימו לב **היכן** הפער גדול. "
  "במסלולים **הכלליים** (שם יושב רוב כספם של החוסכים) הפער זניח: "
  "**+0.15 נק'** בלבד לשנה בקרנות ההשתלמות והתגמולים הכלליות. הפערים הגדולים "
  "צצים דווקא בקטגוריות שבהן טווח הסיכון רחב — פנסיה (+3.0 עד +4.0 נק') "
  "ומסלולי מניות. זה רמז ראשון שהמנוע אינו \"כישרון מתמשך\" אלא **סיכון**.")
w("")

# ---------- risk table ----------
w("## ממצא 3 — המנצחת היא כמעט תמיד הקופה המסוכנת יותר בקטגוריה")
w("")
w("לכל מנצחת נבדק האחוזון שלה בתוך הקטגוריה במונחי **תנודתיות** (סטיית תקן) "
  "ו**חשיפה מנייתית** (50 = ללא הטיה, 100 = המסוכנת ביותר):")
w("")
w("| קטגוריה | אחוזון תנודתיות | אחוזון חשיפה מנייתית |")
w("|---|---:|---:|")
risk_by = {(r["domain"], r["category"]): r for r in risk}
for dom, cat in CAT_ORDER:
    r = risk_by.get((dom, cat))
    if not r: continue
    w(f"| {DOM_HE[dom]} · {cshow(cat)} | {fnum(r['winner_vol_pctile'],'')} | {fnum(r['winner_equity_pctile'],'')} |")
pooled = risk_by.get(("POOLED", ""))
if pooled:
    w(f"| **משוקלל (כל הקטגוריות)** | **{fnum(pooled['winner_vol_pctile'],'')}** | "
      f"**{fnum(pooled['winner_equity_pctile'],'')}** |")
w("")
w("**המסקנה מהטבלה:** המנצחת של אשתקד יושבת בממוצע באחוזון תנודתיות ~67 — כלומר "
  "מי שרודף אחרי המקום הראשון בוחר שיטתית קופה **מסוכנת מהממוצע**. בפנסיה זה חד "
  "במיוחד: המנצחות הן כמעט תמיד מסלולי מניות / עוקבי S&P 500. בשוק שברובו עלה "
  "(2011–2025), הקופה המסוכנת מרוויחה יותר בממוצע — זו **פרמיית סיכון ותופעת שוק "
  "עולה, לא הוכחה לכישרון**. וכשהשוק מתהפך, אותה קופה צונחת לתחתית (ראו למשל את "
  "מסלול ה-S&P 500 שהוביל ב-2014 וצנח למקום 54 מתוך 64 ב-2015).")
w("")

# ---------- per-category tracking tables ----------
w("## מעקב מפורט לפי קטגוריה")
w("")
w("לכל שנת איתות: הקופה שהובילה, תשואתה, ובשלוש השנים שאחרי — התשואה והדירוג "
  "(מקום מתוך סך הקופות בקטגוריה). \"—\" = אין די נתונים / הקופה נסגרה או מוזגה.")
w("")
ev_by = defaultdict(list)
for e in events:
    ev_by[(e["domain"], e["category"])].append(e)

def cell(e, k):
    st = e.get(f"y{k}_status")
    if st == "present":
        return f"{e[f'y{k}_return']}% · {e[f'y{k}_rank']}/{e[f'y{k}_n']}"
    if st == "absent":
        return "נסגרה/מוזגה"
    return "—"

for dom, cat in CAT_ORDER:
    rows = sorted(ev_by.get((dom, cat), []), key=lambda x: int(x["signal_year"]))
    if not rows: continue
    w(f"### {DOM_HE[dom]} · {cshow(cat)}")
    w("")
    w("| שנת איתות | הקופה שנבחרה | תשואת האיתות | שנה +1 (תשואה·דירוג) | שנה +2 | שנה +3 |")
    w("|---|---|---:|---|---|---|")
    for e in rows:
        name = e["winner_name"][:42]
        w(f"| {e['signal_year']} | {name} | {e['signal_return']}% | "
          f"{cell(e,1)} | {cell(e,2)} | {cell(e,3)} |")
    w("")

# ---------- conclusion ----------
w("## מסקנה")
w("")
w("**מעבר לקופה שהובילה בשנה הקודמת אינו מייצר יתרון אמין לאורך זמן.** שלושת "
  "הממצאים מצטרפים לתמונה אחת:")
w("")
w("1. **ההובלה מתפוגגת.** המנצחת נוחתת בשנה שאחרי סביב האחוזון ~60 ומתכנסת חזרה "
  "לכיוון הממוצע; רק כ-12% חוזרות למקום הראשון, וכ-40% צונחות למחצית התחתונה.")
w("2. **הפער הכספי הוא בעיקר סיכון.** ה\"רדיפה\" מובילה שיטתית לקופות תנודתיות "
  "יותר (אחוזון ~67), ובשוק עולה הן מרוויחות יותר בממוצע — פרמיית סיכון, לא "
  "כישרון. במסלולים הכלליים, שם טווח הסיכון צר, ה\"יתרון\" מתאדה לכ-0.15 נק' לשנה.")
w("3. **הרדיפה מרכזת סיכון.** היא כולאת את החוסך בקופה בודדת ומסוכנת, וחושפת "
  "אותו לתהפוכות חדות (המסלול שהוביל אשתקד עלול להיות התחתון של השנה הבאה).")
w("")
w("**השורה התחתונה לחוסך:** בחירת קופה לפי טבלת התשואות של אשתקד היא רדיפה אחרי "
  "העבר. עדיף לבחור מסלול ברמת סיכון שמתאימה לגיל ולצרכים, עם דמי ניהול נמוכים, "
  "ולהחזיק אותו בעקביות — במקום לקפוץ מדי שנה אל כוכב התשואות של אתמול.")
w("")
w("---")
w("*כל הנתונים, הקוד והטבלאות בתיקיית `analysis/`. להרצה חוזרת: "
  "`build_annual.py` → `chase_analysis.py` → `risk_check.py` → `make_report.py`.*")

out = os.path.join(HERE, "REPORT_he.md")
open(out, "w", encoding="utf-8").write("\n".join(lines))
print("wrote", out)
